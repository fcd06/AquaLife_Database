SELECT 
    CASE 
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 0 AND 10 THEN "0-10"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 11 AND 20 THEN "11-20"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 21 AND 30 THEN "21-30"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 31 AND 40 THEN "31-40"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 41 AND 50 THEN "41-50"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 51 AND 60 THEN "51-60"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 61 AND 70 THEN "61-70"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 71 AND 80 THEN "71-80"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 81 AND 90 THEN "81-90"
        ELSE "+90"
    END AS Rango_Edad,
    COUNT(*) as Cantidad_Usuarios,
    ROUND(COUNT(*)/(SELECT COUNT(*) FROM Usuario) * 100, 2) as Porcentaje
    FROM Usuario
    GROUP BY Rango_Edad
    ORDER BY Rango_Edad;