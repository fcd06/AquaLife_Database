SELECT IDU, Nombre, FechaDeNacimiento,
    CASE 
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 0 AND 10.99 THEN "0_10"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 11 AND 20.99 THEN "11_20"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 21 AND 30.99 THEN "21_30"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 31 AND 40.99 THEN "31_40"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 41 AND 50.99 THEN "41_50"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 51 AND 60.99 THEN "51_60"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 61 AND 70.99 THEN "61_70"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 71 AND 80.99 THEN "71_80"
        WHEN TIMESTAMPDIFF(YEAR, FechaDeNacimiento, DATE('2026-12-31')) BETWEEN 91 AND 90.99 THEN "81_90"
        ELSE "+90"
    END AS Rango_edad
    FROM Usuario;
    
    
